// look mode: 3 moments x 5 internal resolutions, 3 s each after a 0.5 s gap
static const int look_k[5] = {16, 14, 12, 11, 10};
static const float look_t[3] = {26, 60, 88};
static U look_fb, look_loc;

static void frame(void)
{
	if (!look) {
		double t0 = now();
		printf_("GL: %s | %s | %s | GLSL %s\n", glGetString(0x1F00), glGetString(0x1F01), glGetString(0x1F02), glGetString(0x8B8C));
		printf_("screen %dx%d, window %dx%d\n", glutGet(200), glutGet(201), glutGet(102), glutGet(103));
#ifdef __APPLE__
		printf_("short framework paths: GLUT %s, OpenGL %s, AudioToolbox %s\n",
			dlopen(FWK "GLUT.framework/GLUT", 1) ? "ok" : "FAILED", dlopen(FWK "OpenGL.framework/OpenGL", 1) ? "ok" : "FAILED",
			dlopen(FWK "AudioToolbox.framework/AudioToolbox", 1) ? "ok" : "FAILED");
#endif
		printf_("GL errors after start-up: 0x%x\n", err());
		out();
		music();
		printf_("GL errors after the music: 0x%x\n", err());
		out();
		bench();
		printf_("\ndone in %.0f s\n", now() - t0);
		out();
		exit_(0);
	}
	if (!look_fb) {
		U tex;
		look_fb = target(0x8058, W, H, &tex);
		look_loc = glGetUniformLocation(program(visual_src[0]), "u");
		start = now();
	}
	double e = now() - start;
	int seg = (int)(e / 3.5);
	if (seg >= 15) exit_(0);
	double into = e - seg * 3.5;
	int k = look_k[seg % 5], sw = W * k / 16, sh = H * k / 16;
	glBindFramebuffer(0x8D40, look_fb);
	if (into < .5) {
		glClearColor(0, 0, 0, 1);
		glClear(0x4000);
	} else {
		glViewport(0, 0, sw, sh);
		glUniform4f(look_loc, look_t[seg / 5] + (float)(into - .5), sw, sh, 0);
		tri();
	}
	glBindFramebuffer(0x8CA9, 0);
	glBlitFramebuffer(0, 0, sw, sh, 0, 0, glutGet(102), glutGet(103), 0x4000, 0x2601);
	glutSwapBuffers();
}

