// look mode: 3 moments x 5 internal resolutions, 3 s each after a 0.5 s gap
static const int look_k[5] = {16, 14, 12, 11, 10};
static const float look_t[3] = {26, 60, 88};
static U look_fb, look_loc;

// play mode: per scene frames, time, frames over 20 ms (missed a 60 Hz refresh), slowest
static const float scene_end[5] = {48, 80, 96, 128, 146};
static const char *scene_name[5] = {"horizon (0:00)", "tunnel 1 (0:48)", "atom (1:20)", "tunnel 2 (1:36)", "outro (2:08)"};
static int sc_frames[5], sc_slow[5], play_s;
static double sc_time[5], sc_worst[5], play_last;
static U play_fb, play_loc;
static int swaps;

static void play_frame(void)
{
	int ww = glutGet(102), wh = glutGet(103);
	if (!play_fb) {
		U tex;
		play_fb = target(0x8058, W, H, &tex);
		play_loc = glGetUniformLocation(program(visual_src[play_v]), "u");
		glViewport(0, 0, 1, 1);
		glUniform4f(play_loc, 12, 1, 1, 0);
		tri();
		glFinish();   // (compiles)
		start = play_last = now();
	}
	double t = now(), e = t - start, dt = t - play_last;
	play_last = t;
	if (e > .5) {   // the interval that just ended belongs to the previous frame's scene
		sc_frames[play_s]++;
		sc_time[play_s] += dt;
		sc_slow[play_s] += dt > .020;
		if (dt > sc_worst[play_s]) sc_worst[play_s] = dt;
	}
	if (e > 146) {
		printf_("\nplay: %s at %d/16 of %dx%d\nscene             fps  frames over 20 ms  slowest frame\n", visual_name[play_v], play_k, ww, wh);
		for (int s = 0; s < 5; s++)
			printf_("%-16s %5.1f  %10.0f %%  %10.0f ms\n", scene_name[s], sc_frames[s] / sc_time[s],
				100. * sc_slow[s] / sc_frames[s], sc_worst[s] * 1e3);
		out();
		exit_(0);
	}
	for (play_s = 0; play_s < 4 && e >= scene_end[play_s]; play_s++)
		;
	int sw = ww * play_k / 16, sh = wh * play_k / 16;
	glBindFramebuffer(0x8D40, play_k < 16 ? play_fb : 0);   // 16: straight into the window, as the intro
	glViewport(0, 0, sw, sh);
	glUniform4f(play_loc, e, sw, sh, 0);
	tri();
	if (play_k < 16) {
		glBindFramebuffer(0x8CA9, 0);
		glBlitFramebuffer(0, 0, sw, sh, 0, 0, ww, wh, 0x4000, 0x2601);
	}
	glutSwapBuffers();
}

static void frame(void)
{
	if (play) {
		play_frame();
		return;
	}
	if (!look && !swaps) start = now();
	if (!look && now() - start < 1.5) {   // first 1.5 s: does swapping wait for the display?
		glBindFramebuffer(0x8D40, 0);
		glClearColor(0, 0, 0, 1);
		glClear(0x4000);
		glutSwapBuffers();
		swaps++;
		return;
	}
	if (!look) {
		double t0 = now();
		printf_("GL: %s | %s | %s | GLSL %s\n", glGetString(0x1F00), glGetString(0x1F01), glGetString(0x1F02), glGetString(0x8B8C));
		printf_("screen %dx%d, window %dx%d\n", glutGet(200), glutGet(201), glutGet(102), glutGet(103));
#ifdef __APPLE__
		printf_("short framework paths: GLUT %s, OpenGL %s, AudioToolbox %s\n",
			dlopen(FWK "GLUT.framework/GLUT", 1) ? "ok" : "FAILED", dlopen(FWK "OpenGL.framework/OpenGL", 1) ? "ok" : "FAILED",
			dlopen(FWK "AudioToolbox.framework/AudioToolbox", 1) ? "ok" : "FAILED");
#endif
		printf_("window: %d buffer swaps in the first 1.5 s (%s)\n", swaps,
			swaps < 400 ? "synchronized with the display" : "not synchronized with the display");
		printf_("GL errors after start-up: 0x%x\n", err());
		out();
		music();
		printf_("GL errors after the music: 0x%x\n", err());
		out();
		bench();
		printf_("\ndone in %.0f s\n", now() - t0);
		out();
		exit_(0);
	}
	if (!look_fb) {
		U tex;
		look_fb = target(0x8058, W, H, &tex);
		look_loc = glGetUniformLocation(program(visual_src[0]), "u");
		start = now();
	}
	double e = now() - start;
	int seg = (int)(e / 3.5);
	if (seg >= 15) exit_(0);
	double into = e - seg * 3.5;
	int k = look_k[seg % 5], sw = W * k / 16, sh = H * k / 16;
	glBindFramebuffer(0x8D40, look_fb);
	if (into < .5) {
		glClearColor(0, 0, 0, 1);
		glClear(0x4000);
	} else {
		glViewport(0, 0, sw, sh);
		glUniform4f(look_loc, look_t[seg / 5] + (float)(into - .5), sw, sh, 0);
		tri();
	}
	glBindFramebuffer(0x8CA9, 0);
	glBlitFramebuffer(0, 0, sw, sh, 0, 0, glutGet(102), glutGet(103), 0x4000, 0x2601);
	glutSwapBuffers();
}

