// Apple SDK (every function comes from dlopen/dlsym, like src/mac/main.asm)
// and also builds a Linux twin with freeglut, for testing it on a PC.
//
//   ./macbench          timings: takes a minute or two, prints a table
//   ./macbench look     the visuals at 5 internal resolutions (to choose the
//                       smallest acceptable one); any key quits
//   The Linux twin also takes a render size: "bench 640 360".
//
// Everything is rendered offscreen into a framebuffer object of the screen
// size and timed with glFinish, so the display's refresh rate does not matter.
