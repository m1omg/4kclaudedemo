static double now(void)
{
#ifdef __APPLE__
	return clock_ns(8) * 1e-9;   // CLOCK_UPTIME_RAW
#else
	long ts[2];
	clock_gettime_(1, ts);       // CLOCK_MONOTONIC
	return ts[0] + ts[1] * 1e-9;
#endif
}

static void out(void) { fflush_(0); }

static U shader(U type, const char *src)
{
	U s = glCreateShader(type);
	int ok = 0;
	glShaderSource(s, 1, &src, 0);
	glCompileShader(s);
	glGetShaderiv(s, 0x8B81, &ok);   // GL_COMPILE_STATUS
	if (!ok) {
		glGetShaderInfoLog(s, sizeof log_, 0, log_);
		printf_("shader compile FAILED:\n%s\n", log_);
	}
	return s;
}

// program with the intro's vertex shader; returns 0 on failure
static U program(const char *fs)
{
	U p = glCreateProgram();
	int ok = 0;
	glAttachShader(p, shader(0x8B31, vs_src));
	glAttachShader(p, shader(0x8B30, fs));
	glLinkProgram(p);
	glGetProgramiv(p, 0x8B82, &ok);   // GL_LINK_STATUS
	if (!ok) {
		glGetProgramInfoLog(p, sizeof log_, 0, log_);
		printf_("program link FAILED:\n%s\n", log_);
		return 0;
	}
	glUseProgram(p);
	return p;
}

static void tri(void) { glDrawArrays(4, 0, 3); }   // GL_TRIANGLES

// clears pending GL errors, returns the first one
static U err(void)
{
	U e = glGetError(), f = e;
	while (f) f = glGetError();
	return e;
}

// offscreen render target: texture + framebuffer object
static U target(U ifmt, int w, int h, U *tex)
{
	U fb;
	glGenTextures(1, tex);
	glBindTexture(0x0DE1, *tex);
	glTexImage2D(0x0DE1, 0, ifmt, w, h, 0, 0x1908, ifmt == 0x8058 ? 0x1401 : 0x1406, 0);
	glGenFramebuffers(1, &fb);
	glBindFramebuffer(0x8D40, fb);
	glFramebufferTexture2D(0x8D40, 0x8CE0, 0x0DE1, *tex, 0);
	U st = glCheckFramebufferStatus(0x8D40);
	if (st != 0x8CD5) printf_("framebuffer %dx%d format 0x%x NOT complete: 0x%x\n", w, h, ifmt, st);
	return fb;
}

// ms per frame of the current program at time t, rendered at w x h: the
// fastest of 3 batches (each at least min_s / 3 and 2 frames), so that
// other programs running meanwhile distort it less
static double timeit(int loc, float t, int w, int h, double min_s)
{
	glViewport(0, 0, w, h);
	glUniform4f(loc, t, w, h, 0);
	tri();
	glFinish();   // warm-up at this size
	double best = 1e9;
	for (int b = 0; b < 3; b++) {
		int n = 0;
		double t0 = now(), t1;
		do {
			tri();
			glFinish();
			n++;
			t1 = now();
		} while (t1 - t0 < min_s / 3 || n < 2);
		if ((t1 - t0) / n < best) best = (t1 - t0) / n;
	}
	return best * 1000;
}

static void music(void)
{
	U tex, fb = target(0x8814, 1024, ROWS, &tex);   // RGBA32F, as in the intro
	double t0 = now();
	U p = program(music_src);
	double t1 = now();
	if (!p) return;
	glViewport(0, 0, 1, 1);
	tri();
	glFinish();
	double t2 = now();
	glViewport(0, 0, 1024, ROWS);
	tri();
	glFinish();
	double t3 = now();
	glReadPixels(0, 0, 1024, ROWS, 0x1908, 0x1406, song);
	double t4 = now(), band = 0;
	printf_("music: compile+link %.0f ms, first tiny draw %.0f ms, render %.0f ms, readback %.0f ms\n",
		(t1 - t0) * 1e3, (t2 - t1) * 1e3, (t3 - t2) * 1e3, (t4 - t3) * 1e3);
	// the same in 8 horizontal bands (gl_FragCoord is window relative)
	int bh = (ROWS + 7) / 8;
	double tb = now();
	for (int b = 0; b < 8; b++) {
		double s = now();
		glViewport(0, b * bh, 1024, bh);
		tri();
		glFinish();
		double e = now() - s;
		if (e > band) band = e;
	}
	double total = now() - tb;
	glReadPixels(0, 0, 1024, ROWS, 0x1908, 0x1406, song2);
	long diff = 0;
	double rms = 0;
	for (long i = 0; i < (long)SONG_SAMPLES * 2; i++) {
		U a = ((U *)song)[i], b = ((U *)song2)[i];
		diff += a != b;
		rms += (double)song[i] * song[i];
	}
	printf_("music in 8 bands: slowest band %.0f ms, all %.0f ms, identical to one draw: %s\n",
		band * 1e3, total * 1e3, diff ? "NO" : "yes");
	// rms of the llvmpipe reference: 0.2130 (NVIDIA: 0.2130)
	printf_("music check: rms %.4f (reference 0.2130), samples %.5f %.5f %.5f %.5f\n",
		rms > 0 ? __builtin_sqrt(rms / ((double)SONG_SAMPLES * 2)) : 0., song[176400 * 2], song[176400 * 2 + 1],
		song[2646000 * 2], song[2646000 * 2 + 1]);
	glDeleteProgram(p);
	(void)fb;
}

// the intro's speed test (src/mac/main.asm with SCALE): 3 frames of 1:28 at
// half size, the fastest in whole ms from glutGet, k = the largest k (11..16)
// with k * k * ms <= 2304 (about 36 ms per frame at full size)
static void speedtest(U p, int loc, const char *when)
{
	int sw = W / 2, sh = H / 2, best = 1 << 30, last, k = 16;
	double bestp = 1e9, tl;
	glUseProgram(p);
	glViewport(0, 0, sw, sh);
	glUniform4f(loc, 88, sw, sh, 0);
	tri();
	glFinish();
	last = glutGet(700);
	tl = now();
	for (int i = 0; i < 3; i++) {
		tri();
		glFinish();
		int t = glutGet(700);
		double tp = now();
		if (t - last < best) best = t - last;
		if (tp - tl < bestp) bestp = tp - tl;
		last = t;
		tl = tp;
	}
	while (k > 11 && k * k * best > 2304) k--;
	printf_("the intro's speed test (%s): fastest half-size frame of 1:28 %d ms (exactly %.1f ms) -> render size %d/16\n",
		when, best, bestp * 1e3, k);
	out();
}

// renders 1:28 at full size without a break for secs seconds, printing the
// average ms per frame every 3 s (the GPU's clock drops as it heats up)
static void heat(U p, int loc, double secs)
{
	glUseProgram(p);
	glViewport(0, 0, W, H);
	glUniform4f(loc, 88, W, H, 0);
	printf_("heating the GPU up: 1:28 at full size for %.0f s, ms per frame every 3 s:\n ", secs);
	out();
	double t0 = now(), w0 = t0;
	int n = 0;
	while (now() - t0 < secs) {
		tri();
		glFinish();
		n++;
		double t = now();
		if (t - w0 >= 3) {
			printf_(" %.1f", (t - w0) / n * 1e3);
			out();
			w0 = t;
			n = 0;
		}
	}
	printf_("\n");
}

static void bench(void)
{
	U tex, fb = target(0x8058, W, H, &tex);   // RGBA8 at the screen size
	static U prog[NVAR];
	static int loc[NVAR];
	static double ms[NVAR][NM];
	for (int v = 0; v < NVAR; v++) {
		double t0 = now();
		prog[v] = program(visual_src[v]);
		double t1 = now();
		if (!prog[v]) { printf_("%s: FAILED\n", visual_name[v]); exit_(1); }
		loc[v] = glGetUniformLocation(prog[v], "u");
		glViewport(0, 0, 1, 1);
		glUniform4f(loc[v], 12, 1, 1, 0);
		tri();
		glFinish();
		double t2 = now();
		printf_("%-12s compile+link %4.0f ms, first draw %4.0f ms\n", visual_name[v], (t1 - t0) * 1e3, (t2 - t1) * 1e3);
		for (int m = 0; m < NM; m++) ms[v][m] = 1e9;
	}
	out();
	speedtest(prog[0], loc[0], "now");
	heat(prog[0], loc[0], 30);
	speedtest(prog[0], loc[0], "hot");
	// 3 rounds; in each, every moment is measured with all variants in turn,
	// a few seconds apart: the fastest round counts
	printf_("measuring %d variants at %d moments, 3 rounds ", NVAR, NM);
	out();
	for (int r = 0; r < 3; r++) {
		for (int m = 0; m < NM; m++)
			for (int v = 0; v < NVAR; v++) {
				glUseProgram(prog[v]);
				double x = timeit(loc[v], moments[m], W, H, .1);
				if (x < ms[v][m]) ms[v][m] = x;
			}
		printf_(".");
		out();
	}
	printf_("\n\nms per frame at %dx%d (hot):\nvariant     ", W, H);
	for (int m = 0; m < NM; m++) printf_(" %2d:%02d", (int)moments[m] / 60, (int)moments[m] % 60);
	printf_("  weighted  vs current\n");
	double base = 0;
	for (int v = 0; v < NVAR; v++) {
		double a = 0, wsum = 0;
		printf_("%-11s ", visual_name[v]);
		for (int m = 0; m < NM; m++) {
			printf_("%6.1f", ms[v][m]);
			a += ms[v][m] * weights[m];
			wsum += weights[m];
		}
		a /= wsum;
		if (!v) base = a;
		printf_("  %8.1f  %+5.1f %%\n", a, (a / base - 1) * 100);
	}
	speedtest(prog[0], loc[0], "at the end");
	(void)fb;
}

