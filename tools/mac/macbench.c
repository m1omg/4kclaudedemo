// Development tool (NOT part of the intro): measures BRANA's shaders on the
// GPU of a Mac. tools/mac/build.sh cross-compiles it on Linux without the
// Apple SDK (every function comes from dlopen/dlsym, like src/mac/main.asm)
// and also builds a Linux twin with freeglut, for testing it on a PC.
//
//   ./macbench               timings, about 2 minutes. A laptop slows down when
//                            it gets hot, so it first heats the GPU up for 30 s,
//                            then measures the shader variants taking turns
//                            (heat affects them all alike); prints tables
//   ./macbench look          the visuals at 5 internal resolutions (to choose
//                            the smallest acceptable one); any key quits
//   ./macbench play [v] [k]  the intro's visuals in real time (no sound) with
//                            shader variant v (name or number, default current)
//                            at k/16 of the screen resolution (default 16),
//                            then the frame rate of every scene; any key quits
//   The Linux twin also takes a render size: "bench 640 360".
//
// The timings render offscreen into a framebuffer object of the screen size
// and wait for each frame with glFinish, so the display's refresh rate does
// not matter.
