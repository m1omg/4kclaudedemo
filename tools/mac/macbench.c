static void *lib(const char *name)
{
	void *h = dlopen(name, 1);
	if (!h) { printf_("cannot load %s\n", name); exit_(1); }
	return h;
}

static void *sym(void *h, const char *name)
{
	void *p = dlsym(h, name);
	if (!p) { printf_("missing function %s\n", name); exit_(1); }
	return p;
}
#define LOAD(h, f) (*(void **)&f = sym(h, #f))

static double now(void)
{
#ifdef __APPLE__
	return clock_ns(8) * 1e-9;   // CLOCK_UPTIME_RAW
#else
	long ts[2];
	clock_gettime_(1, ts);       // CLOCK_MONOTONIC
	return ts[0] + ts[1] * 1e-9;
#endif
}

static void out(void) { fflush_(0); }

static U shader(U type, const char *src)
{
	U s = glCreateShader(type);
	int ok = 0;
	glShaderSource(s, 1, &src, 0);
	glCompileShader(s);
	glGetShaderiv(s, 0x8B81, &ok);   // GL_COMPILE_STATUS
	if (!ok) {
		glGetShaderInfoLog(s, sizeof log_, 0, log_);
		printf_("shader compile FAILED:\n%s\n", log_);
	}
	return s;
}

// program with the intro's vertex shader; returns 0 on failure
static U program(const char *fs)
{
	U p = glCreateProgram();
	int ok = 0;
	glAttachShader(p, shader(0x8B31, vs_src));
	glAttachShader(p, shader(0x8B30, fs));
	glLinkProgram(p);
	glGetProgramiv(p, 0x8B82, &ok);   // GL_LINK_STATUS
	if (!ok) {
		glGetProgramInfoLog(p, sizeof log_, 0, log_);
		printf_("program link FAILED:\n%s\n", log_);
		return 0;
	}
	glUseProgram(p);
	return p;
}

static void tri(void) { glDrawArrays(4, 0, 3); }   // GL_TRIANGLES

// clears pending GL errors, returns the first one
static U err(void)
{
	U e = glGetError(), f = e;
	while (f) f = glGetError();
	return e;
}

// offscreen render target: texture + framebuffer object
static U target(U ifmt, int w, int h, U *tex)
{
	U fb;
	glGenTextures(1, tex);
	glBindTexture(0x0DE1, *tex);
	glTexImage2D(0x0DE1, 0, ifmt, w, h, 0, 0x1908, ifmt == 0x8058 ? 0x1401 : 0x1406, 0);
	glGenFramebuffers(1, &fb);
	glBindFramebuffer(0x8D40, fb);
	glFramebufferTexture2D(0x8D40, 0x8CE0, 0x0DE1, *tex, 0);
	U st = glCheckFramebufferStatus(0x8D40);
	if (st != 0x8CD5) printf_("framebuffer %dx%d format 0x%x NOT complete: 0x%x\n", w, h, ifmt, st);
	return fb;
}

// ms per frame of the current program at time t, rendered at w x h: the
// fastest of 3 batches (each at least min_s / 3 and 2 frames), so that
// other programs running meanwhile distort it less
static double timeit(int loc, float t, int w, int h, double min_s)
{
	glViewport(0, 0, w, h);
	glUniform4f(loc, t, w, h, 0);
	tri();
	glFinish();   // warm-up at this size
	double best = 1e9;
	for (int b = 0; b < 3; b++) {
		int n = 0;
		double t0 = now(), t1;
		do {
			tri();
			glFinish();
			n++;
			t1 = now();
		} while (t1 - t0 < min_s / 3 || n < 2);
		if ((t1 - t0) / n < best) best = (t1 - t0) / n;
	}
	return best * 1000;
}

static void music(void)
{
	U tex, fb = target(0x8814, 1024, ROWS, &tex);   // RGBA32F, as in the intro
	double t0 = now();
	U p = program(music_src);
	double t1 = now();
	if (!p) return;
	glViewport(0, 0, 1, 1);
	tri();
	glFinish();
	double t2 = now();
	glViewport(0, 0, 1024, ROWS);
	tri();
	glFinish();
	double t3 = now();
	glReadPixels(0, 0, 1024, ROWS, 0x1908, 0x1406, song);
	double t4 = now(), band = 0;
	printf_("music: compile+link %.0f ms, first tiny draw %.0f ms, render %.0f ms, readback %.0f ms\n",
		(t1 - t0) * 1e3, (t2 - t1) * 1e3, (t3 - t2) * 1e3, (t4 - t3) * 1e3);
	// the same in 8 horizontal bands (gl_FragCoord is window relative)
	int bh = (ROWS + 7) / 8;
	double tb = now();
	for (int b = 0; b < 8; b++) {
		double s = now();
		glViewport(0, b * bh, 1024, bh);
		tri();
		glFinish();
		double e = now() - s;
		if (e > band) band = e;
	}
	double total = now() - tb;
	glReadPixels(0, 0, 1024, ROWS, 0x1908, 0x1406, song2);
	long diff = 0;
	double rms = 0;
	for (long i = 0; i < (long)SONG_SAMPLES * 2; i++) {
		U a = ((U *)song)[i], b = ((U *)song2)[i];
		diff += a != b;
		rms += (double)song[i] * song[i];
	}
	printf_("music in 8 bands: slowest band %.0f ms, all %.0f ms, identical to one draw: %s\n",
		band * 1e3, total * 1e3, diff ? "NO" : "yes");
	// rms of the llvmpipe reference: 0.2130 (NVIDIA: 0.2130)
	printf_("music check: rms %.4f (reference 0.2130), samples %.5f %.5f %.5f %.5f\n",
		rms > 0 ? __builtin_sqrt(rms / ((double)SONG_SAMPLES * 2)) : 0., song[176400 * 2], song[176400 * 2 + 1],
		song[2646000 * 2], song[2646000 * 2 + 1]);
	glDeleteProgram(p);
	(void)fb;
}

static void bench(void)
{
	U tex, fb = target(0x8058, W, H, &tex);   // RGBA8 at the screen size
	static double ms[NVAR][2][8];
	for (int v = 0; v < NVAR; v++) {
		double t0 = now();
		U p = program(visual_src[v]);
		double t1 = now();
		if (!p) { printf_("%s: FAILED\n", visual_name[v]); continue; }
		int loc = glGetUniformLocation(p, "u");
		glViewport(0, 0, 1, 1);
		glUniform4f(loc, 12, 1, 1, 0);
		tri();
		glFinish();
		double t2 = now();
		if (!v) printf_("uniform location of u: %d\n", loc);
		printf_("%-12s compile+link %5.0f ms, first draw %5.0f ms ...", visual_name[v], (t1 - t0) * 1e3, (t2 - t1) * 1e3);
		out();
		for (int s = 0; s < 2; s++)
			for (int m = 0; m < 8; m++)
				ms[v][s][m] = timeit(loc, moments[m], s ? W / 2 : W, s ? H / 2 : H, .3);
		printf_(" done\n");
		out();
		glDeleteProgram(p);
	}
	for (int s = 0; s < 2; s++) {
		printf_("\nms per frame at %dx%d%s:\nvariant      ", s ? W / 2 : W, s ? H / 2 : H, s ? " (half size)" : "");
		for (int m = 0; m < 8; m++) printf_("%5.0fs", moments[m]);
		printf_("  weighted\n");
		for (int v = 0; v < NVAR; v++) {
			double a = 0, wsum = 0;
			printf_("%-12s ", visual_name[v]);
			for (int m = 0; m < 8; m++) {
				printf_("%6.1f", ms[v][s][m]);
				a += ms[v][s][m] * weights[m];
				wsum += weights[m];
			}
			printf_("  %6.1f\n", a / wsum);
		}
	}
	// the render target and the upscale that the resolution scaling would use
	U p = program(visual_src[0]);
	int loc = glGetUniformLocation(p, "u"), sw = W * 11 / 16, sh = H * 11 / 16;
	printf_("\nrender at 11/16 size (%dx%d) + upscale to the window, current shader, t=26:\n", sw, sh);
	printf_("  GL errors before this test: 0x%x\n", err());
	for (int k = 0; k < 4; k++) {   // both formats twice, only the second round is printed (warm-up)
		U ifmt = k & 1 ? 0x8814 : 0x8058, t2, fb2 = target(ifmt, W, H, &t2);
		double d = timeit(loc, 26, sw, sh, .3), b = 0;
		int n = 0;
		double t0 = now();
		do {
			glBindFramebuffer(0x8CA9, 0);   // draw: window, read: fb2
			glBlitFramebuffer(0, 0, sw, sh, 0, 0, W, H, 0x4000, 0x2601);
			glFinish();
			n++;
			b = now() - t0;
		} while (b < .2 || n < 2);
		if (k > 1) printf_("  %-7s render %.1f ms, blit %.2f ms, GL error 0x%x\n", k & 1 ? "RGBA32F" : "RGBA8", d, b / n * 1e3, err());
		glBindFramebuffer(0x8D40, fb2);
	}
	// the intro's plan: re-specify the (attached) music texture at the screen size
	U mt, mf = target(0x8814, 1024, ROWS, &mt);
	glTexImage2D(0x0DE1, 0, 0x8058, W, H, 0, 0x1908, 0x1401, 0);
	U st = glCheckFramebufferStatus(0x8D40);
	timeit(loc, 26, sw, sh, .05);
	glBindFramebuffer(0x8CA9, 0);
	glBlitFramebuffer(0, 0, sw, sh, 0, 0, W, H, 0x4000, 0x2601);
	glFinish();
	printf_("  attached texture re-specified at screen size: framebuffer 0x%x%s, draw+blit GL error 0x%x\n", st,
		st == 0x8CD5 ? " (complete)" : " (NOT complete)", err());
	(void)fb;
	(void)mf;
}

